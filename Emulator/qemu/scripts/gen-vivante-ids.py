#!/usr/bin/env python3
#
# Generate hw/kick/vivante-ids.h from the galcore feature database.
#
# The database (hal/kernel/inc/gc_feature_database.h) ships with the Vivante
# kernel driver used by the KICK firmware, Freescale/kernel-module-imx-gpu-viv
# at commit 5c8eb7b0576dc2348fb206945ce13e41d0837cf1 (galcore 6.4.3.p1).
# Its REG_* columns are, in order, the bits of the HI_CHIP_FEATURE register
# followed by HI_CHIP_MINOR_FEATURE_0..6, 32 bits each, so the register values
# the hardware reports can be reconstructed from a database row. galcore
# itself identifies the chip by model, revision, product, ECO and customer
# ID and then uses the database; the feature registers matter for etnaviv
# and for galcore's _IsGPUPresent() signature check.
#
# Usage: gen-vivante-ids.py <gc_feature_database.h> > vivante-ids.h
#
# SPDX-License-Identifier: GPL-2.0-or-later

import re
import sys

# (C name, database entry comment) of the cores on the i.MX8M Mini.
CHIPS = [
    ("gc600_4653", "gc7000nanoultra_4_6_5_rc3a"),
    ("gc520_5341", "gc520l_5341_rc1b"),
]

FEATURE_REGS = ["chip_features"] + ["minor_features%d" % i for i in range(7)]


def parse(path):
    src = open(path).read()
    st = src[src.index("typedef struct"):]
    st = st[:st.index("} gcsFEATURE_DATABASE")]
    fields = re.findall(r"(?:gct\w+|const char)\s+\*?\s*(\w+)(?::\d+)?;", st)
    body = src[src.index("static gcsFEATURE_DATABASE gChipInfo[]"):]
    parts = re.split(r"\n    /\* (\w+) \*/\n", body)
    rows = {}
    for i in range(1, len(parts), 2):
        txt = parts[i + 1][:parts[i + 1].index("\n    },")]
        vals = re.findall(r'^\s+(0x[0-9a-fA-F]+|"[^"]*"|\d+),', txt, re.M)
        if len(vals) != len(fields):
            sys.exit("field count mismatch in %s" % parts[i])
        rows.setdefault(parts[i], dict(zip(fields, vals)))
    return fields, rows


def main():
    fields, rows = parse(sys.argv[1])
    reg_fields = [f for f in fields if f.startswith("REG_")]
    out = []
    out.append("/*")
    out.append(" * Vivante GPU identification of the i.MX8M Mini cores.")
    out.append(" *")
    out.append(" * Generated by Emulator/qemu/scripts/gen-vivante-ids.py from the galcore")
    out.append(" * 6.4.3.p1 feature database (kernel-module-imx-gpu-viv 5c8eb7b0). Do not")
    out.append(" * edit by hand.")
    out.append(" *")
    out.append(" * SPDX-License-Identifier: GPL-2.0-or-later")
    out.append(" */")
    out.append("")
    out.append("#ifndef KICK_VIVANTE_IDS_H")
    out.append("#define KICK_VIVANTE_IDS_H")
    out.append("")
    for name, entry in CHIPS:
        row = rows[entry]
        regs = [0] * len(FEATURE_REGS)
        for bit, f in enumerate(reg_fields):
            if int(row[f], 0):
                regs[bit // 32] |= 1 << (bit % 32)
        up = name.upper()
        out.append("/* database entry %s */" % entry)
        for key in ("chipID", "chipVersion", "productID", "ecoID", "customerID"):
            cname = {"chipID": "MODEL", "chipVersion": "REVISION",
                     "productID": "PRODUCT_ID", "ecoID": "ECO_ID",
                     "customerID": "CUSTOMER_ID"}[key]
            out.append("#define VIV_%s_%-20s 0x%08x" % (up, cname, int(row[key], 0)))
        for r, v in zip(FEATURE_REGS, regs):
            out.append("#define VIV_%s_%-20s 0x%08x" % (up, r.upper(), v))
        out.append("")
    out.append("#endif")
    print("\n".join(out))


if __name__ == "__main__":
    main()
